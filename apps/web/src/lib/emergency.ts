export const EMERGENCY_KEYWORDS = [...EN, ...HI, ...MR];

const norm = (s: string) =>
	s.toLowerCase().normalize('NFC').replace(/[’`]/g, "'").replace(/\s+/g, ' ');
const LATIN = /^[a-z' ]+$/;
const words = EMERGENCY_KEYWORDS.map(norm);

/**
 * True when the text contains an emergency keyword. Keywords must start a word. Latin and short
 * Devanagari keywords must be whole words ("fire" ≠ "fireflies", आग ≠ आगे, पूर ≠ पूरा); longer
 * Devanagari keywords may take suffixes (बुडत → बुडतोय).
 */
export function isEmergency(text: string) {
	const t = ` ${norm(text).replace(/[^\p{L}\p{M}\p{N}' ]+/gu, ' ')} `;
	return words.some((w) =>
		LATIN.test(w) || [...w].length <= 3 ? t.includes(` ${w} `) : t.includes(` ${w}`)
	);
}
